/**
 * Build what the site derives from its own photographs.
 *
 *   node scripts/photo-assets.mjs
 *
 * Run it after adding or replacing a photo in public/images/ghormu. It
 * writes, and both results are committed:
 *
 * - content/photo-placeholders.ts: a tiny blurred copy of every photo,
 *   shown while the real one loads.
 * - public/images/og/<photo>.jpg: the 1200×630 card a link to the site
 *   shows when shared (WhatsApp, Facebook, X), with the Ghormu name on it.
 *   Drawn by Chromium so the Devanagari is shaped exactly as in a browser;
 *   it fetches the site's two typefaces from Google Fonts while it runs.
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const require = createRequire(join(root, "package.json"))
const sharp = require("sharp")
const { chromium } = require("@playwright/test")

const photoDir = join(root, "public", "images", "ghormu")
const cardDir = join(root, "public", "images", "og")
const ids = readdirSync(photoDir)
  .filter((file) => file.endsWith(".webp"))
  .map((file) => file.slice(0, -".webp".length))
  .sort()

// ---------------------------------------------------------------------------
// Blur placeholders
// ---------------------------------------------------------------------------

const placeholders = {}
for (const id of ids) {
  const tiny = await sharp(join(photoDir, `${id}.webp`)).resize(16).webp({ quality: 50 }).toBuffer()
  placeholders[id] = `data:image/webp;base64,${tiny.toString("base64")}`
}

writeFileSync(
  join(root, "content", "photo-placeholders.ts"),
  `/**
 * Generated by scripts/photo-assets.mjs: do not edit. A 16-pixel copy of each
 * photo in public/images/ghormu, blurred and shown while the photo loads.
 */
export const photoPlaceholders: Record<string, string> = ${JSON.stringify(placeholders, null, 2)}
`,
)

// ---------------------------------------------------------------------------
// Share cards
// ---------------------------------------------------------------------------

const logo = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="72" height="72">
  <rect width="32" height="32" rx="8" fill="#1d5c45"/>
  <circle cx="22" cy="10" r="3" fill="#f7f4ec" fill-opacity="0.8"/>
  <path d="M4 25 L12 13 L17 20 L20 16 L28 25 Z" fill="#f7f4ec"/>
</svg>`

// Every use of these photos carries its credit, the share card included.
const credits = { lwnf: "Photo: Little World Nepal France", ply: "Photo: Plein Leurs Yeux" }

const card = (image, credit) => `<!doctype html>
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Mukta:wght@500&family=Noto+Serif+Devanagari:wght@600&display=block">
<style>
  * { margin: 0; box-sizing: border-box; }
  body { width: 1200px; height: 630px; overflow: hidden; position: relative; background: #0f2a1f; }
  img { position: absolute; inset: 0; width: 100%; height: 100%; object-fit: cover; }
  .shade { position: absolute; inset: 0; background:
    linear-gradient(to top, rgba(8, 22, 16, 0.92), rgba(8, 22, 16, 0.45) 42%, rgba(8, 22, 16, 0) 72%),
    linear-gradient(to right, rgba(8, 22, 16, 0.6), rgba(8, 22, 16, 0) 55%); }
  .brand { position: absolute; left: 64px; bottom: 56px; display: flex; align-items: center; gap: 28px; color: #f7f4ec; }
  .name { font-family: "Noto Serif Devanagari", serif; font-weight: 600; font-size: 76px; line-height: 1.1; }
  .site { font-family: "Mukta", sans-serif; font-weight: 500; font-size: 30px; letter-spacing: 0.04em; opacity: 0.85; margin-top: 4px; }
  .credit { position: absolute; right: 40px; bottom: 36px; font-family: "Mukta", sans-serif; font-weight: 500; font-size: 20px; color: #f7f4ec; opacity: 0.75; }
</style></head>
<body>
  <img src="${image}" alt="">
  <div class="shade"></div>
  <div class="brand">${logo}<div><div class="name">घोर्मु</div><div class="site">Ghormu · ghormu.com</div></div></div>
  <div class="credit">${credit}</div>
</body></html>`

mkdirSync(cardDir, { recursive: true })

const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1200, height: 630 } })

for (const id of ids) {
  const photo = readFileSync(join(photoDir, `${id}.webp`)).toString("base64")
  const credit = credits[id.split("-")[0]]
  if (!credit) throw new Error(`No credit known for ${id}: add its source to the credits above.`)

  await page.setContent(card(`data:image/webp;base64,${photo}`, credit), { waitUntil: "networkidle" })
  await page.evaluate(() => document.fonts.ready)

  // Each typeface checked against the text it draws on the card.
  const fonts = await page.evaluate(
    () => document.fonts.check("600 76px 'Noto Serif Devanagari'", "घोर्मु") && document.fonts.check("500 30px Mukta", "Ghormu · ghormu.com Photo"),
  )
  if (!fonts) throw new Error("The card typefaces did not load from Google Fonts; check the connection and run again.")

  const png = await page.screenshot({ type: "png" })
  await sharp(png).jpeg({ quality: 82, mozjpeg: true }).toFile(join(cardDir, `${id}.jpg`))
}

await browser.close()
console.log(`${ids.length} placeholders and share cards written.`)
